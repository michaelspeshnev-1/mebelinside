def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def sect(path, start, stop=None):
    """Дословный кусок файла: от строки, начинающейся с `start`, до строки, начинающейся с любого из `stop`
    (или до следующего заголовка того же/старшего уровня). Разделитель `---` в конце отрезается."""
    lines = read(path).split("\n")
    i = next((n for n, l in enumerate(lines) if l.startswith(start)), None)
    if i is None:
        raise SystemExit(f"{path}: не найден заголовок {start!r}")
    level = len(re.match(r"#*", lines[i]).group(0)) or 9
    stops = [stop] if isinstance(stop, str) else (stop or [])
    j = len(lines)
    in_code = False
    for n in range(i + 1, len(lines)):
        l = lines[n]
        if l.startswith("```"):
            in_code = not in_code
        if in_code:
            continue
        if stops:
            if any(l.startswith(s) for s in stops):
                j = n
                break
        else:
            m = re.match(r"(#+) ", l)
            if m and len(m.group(1)) <= level:
                j = n
                break
    chunk = "\n".join(lines[i:j]).rstrip()
    chunk = re.sub(r"\n---\s*$", "", chunk).rstrip()
    return chunk


def htmlfile(path):
    body = read(path).rstrip()
    assert "```" not in body, path
    return (f"Файл целиком: [{path}]({GH}{path}) · только текст для копирования: {RAW}{path}\n\n"
            f"```html\n{body}\n```")


