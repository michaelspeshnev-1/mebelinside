def card(fn, title, zadanie, do, paste=None, check=None, ne=None, report=None, status=None, time=None):
    CARDS.append(dict(fn=fn, title=title, zadanie=zadanie, do=do, paste=paste, check=check,
                      ne=ne or [], report=report, status=status, time=time))


def demote(text):
    """Заголовки вставленных исходников опускаем на 2 уровня (# → ###), чтобы они не путались
    с разделами карточки; код внутри ``` не трогаем."""
    out, in_code = [], False
    for l in text.split("\n"):
        if l.startswith("```"):
            in_code = not in_code
        elif not in_code and re.match(r"#{1,4} ", l):
            l = "##" + l
        out.append(l)
    return "\n".join(out)


def render(c, idx):
    o = [f"# {c['fn'][:-3]} · {c['title']}", ""]
    meta = f"Задание: {c['zadanie']}"
    if c["time"]:
        meta += f" · ~{c['time']}"
    o.append(meta + f" · Админка: {ADMIN}")
    if c["status"]:
        o += ["", f"> **Статус:** {c['status']}"]
    o += ["", "## Что сделать", ""]
    for n, s in enumerate(c["do"], 1):
        o.append(f"{n}. {s}")
    if c["paste"]:
        o += ["", "## Что вставить", "", demote(c["paste"]), "", "*(конец раздела «Что вставить»)*"]
    o += ["", "## Проверка", ""]
    for s in (c["check"] or []):
        o.append(f"- {s}")
    o.append(f"- Перед проверкой сбросить кэш: {CC}, страницу открывать в новой вкладке.")
    o += ["", "## Нельзя", ""]
    for s in c["ne"] + NE_COMMON:
        o.append(f"- {s}")
    o += ["", "## Отчёт", "", "Одной строкой Михаилу (он перешлёт в «Главный»):", "",
          f"`{c['report']}`", ""]
    nxt = CARDS[idx + 1]["fn"] if idx + 1 < len(CARDS) else None
    o.append(f"Дальше: [{nxt}]({GH}zalivka/{nxt})" if nxt else "Это последняя карточка.")
    o.append("")
    return "\n".join(o)


