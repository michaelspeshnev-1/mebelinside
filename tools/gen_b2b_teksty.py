def faq_html(faq):
    out = ['<section class="mi-faq">', "<h2>Частые вопросы</h2>"]
    for q, a in faq:
        out += [f"<h3>{html.escape(q, quote=False)}</h3>", f"<p>{html.escape(a, quote=False)}</p>"]
    out.append("</section>")
    return "\n".join(out)


def faq_jsonld(faq):
    data = {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": [
            {"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in faq
        ],
    }
    return '<script type="application/ld+json">\n' + json.dumps(data, ensure_ascii=False, indent=1) + "\n</script>"


def check(p):
    errs = []
    if len(p["title"]) > TITLE_MAX:
        errs.append(f"Title {len(p['title'])} > {TITLE_MAX}")
    if len(p["desc"]) > DESC_MAX:
        errs.append(f"Description {len(p['desc'])} > {DESC_MAX}")
    if not 4 <= len(p["faq"]) <= 5:
        errs.append(f"FAQ: {len(p['faq'])} вопросов")
    if errs:
        raise SystemExit(f"{p['url']}: " + "; ".join(errs))


